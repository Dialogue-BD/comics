/* Join the 4Ds recordings on the animation's own timeline. Requires ffmpeg. */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const os = require('node:os');
const {execFileSync} = require('node:child_process');
const root = path.join(__dirname, '..');
const audio = path.join(root, 'audio');
const manifest = require(path.join(audio, 'manifest.json'));

global.window = global;
global.document = {querySelector:()=>null, querySelectorAll:()=>[], addEventListener(){}};
for (const script of ['compass', 'engine', 'intro']) require(path.join(root, script+'.js'));
global.fetch = async () => ({ok:true, json:async()=>manifest});

async function build() {
  await INTRO.ready();
  const rate = 24000;
  const samples = seconds => Math.round(seconds * rate);
  const pcm = Buffer.alloc(samples(INTRO.total()) * 2);
  const durations = {};
  let offset = 0;
  for (const scene of INTRO.SCENES) {
    for (const [index, [text]] of scene.lines.entries()) {
      const key = AFL.audioKey(text);
      const duration = manifest.dur[key];
      if (!(duration > 0)) throw Error('Missing recording for: '+text);
      durations[key] = duration;
      const data = execFileSync('ffmpeg', ['-v','error','-i',path.join(audio,key+'.mp3'),
        '-ac','1','-ar',String(rate),'-f','s16le','pipe:1']);
      if (data.length / 2 > samples(duration + .08)) {
        throw Error('Manifest duration is shorter than the recording: '+text);
      }
      const start = samples(offset + scene._t[index]) * 2;
      const limit = samples(offset + (scene._t[index+1] ?? scene._dur)) * 2;
      if (start + data.length > limit) throw Error('Recording overlaps the next cue: '+text);
      data.copy(pcm, start);
    }
    offset += scene._dur;
  }
  // A seekable output lets the encoder write gapless playback and duration metadata.
  const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'four-ds-film-'));
  let track;
  try {
    const out=path.join(tmp,'track.mp3');
    execFileSync('ffmpeg', ['-v','error','-f','s16le','-ar',String(rate),'-ac','1','-i','pipe:0',
      '-c:a','libmp3lame','-b:a','48k',out], {input:pcm});
    track=fs.readFileSync(out);
  } finally {
    fs.rmSync(tmp,{recursive:true,force:true});
  }
  const version = crypto.createHash('sha256').update(track).digest('hex').slice(0,12);
  fs.writeFileSync(path.join(audio,'four-ds-film.mp3'),track);
  fs.writeFileSync(path.join(audio,'four-ds-film.js'), '/* Generated by tools/build-intro-audio.cjs. */\nwindow.INTRO_AUDIO='+JSON.stringify({
    src:'audio/four-ds-film.mp3?v='+version, dur:durations
  },null,2)+';\n');
  console.log(Object.keys(durations).length+' recordings · '+offset.toFixed(2)+' s · '+Math.round(track.length/1024)+' KiB');
}
build().catch(error => {console.error(error.message);process.exitCode=1;});
