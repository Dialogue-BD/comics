#!/usr/bin/env python3
"""Find the printed title at the top of each Picture This Bangla card (front and
back) and write title-boxes.js for the title speaker button.

  python3 scripts/title_boxes.py            # cwd = picture-this-bangla/

Output: title-boxes.js = window.PTB_TITLE_BOXES = {cardId: {"front": [left, top,
width, height], "back": [...]}} in % of each image.  A card missing from the
file still gets a speaker; the page falls back to the top-right corner.

How it works: the title is the first band of dark ink from the top of the
image.  Rows are scanned from the top; the band ends at the first gap of
blank rows after ink starts.  Columns with ink inside that band give the
left and right edges.  Needs numpy and Pillow only.
"""
import json, os, re
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DARK = 110        # grey level counted as ink
GAP = 0.008       # blank band (fraction of height) that ends the title
LIMIT = 0.16      # never look below this fraction of the height


def box(path):
    im = np.asarray(Image.open(path).convert("L"), dtype=np.uint8)
    h, w = im.shape
    ink = im[: int(h * LIMIT)] < DARK
    rows = ink.sum(1) > max(2, w * 0.002)
    ys = np.flatnonzero(rows)
    if not len(ys):
        return None
    top = ys[0]; gap = max(3, int(h * GAP)); bottom = top
    for y in ys:
        if y - bottom > gap:
            break
        bottom = y
    cols = np.flatnonzero(ink[top:bottom + 1].sum(0) > 0)
    if not len(cols):
        return None
    l, r = cols[0], cols[-1]
    return [round(100 * l / w, 2), round(100 * top / h, 2), round(100 * (r - l + 1) / w, 2), round(100 * (bottom - top + 1) / h, 2)]


def main():
    text = open(os.path.join(HERE, "deck-data.js"), encoding="utf-8").read()
    deck = json.loads(text.split("window.PTB_DECK = ", 1)[1].split(";\nwindow.")[0].strip().rstrip(";"))
    out, missing = {}, []
    for c in deck["cards"]:
        rec = {}
        for side in ("front", "back"):
            b = box(os.path.join(HERE, c[side]))
            if b and b[3] < 12 and b[2] > 5:
                rec[side] = b
        if rec:
            out[c["id"]] = rec
        if len(rec) < 2:
            missing.append(c["id"])
    with open(os.path.join(HERE, "title-boxes.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/title_boxes.py from the card images. Do not edit by hand.\n")
        f.write("window.PTB_TITLE_BOXES = " + json.dumps(out, separators=(",", ":")) + ";\n")
    print(f"title-boxes.js: {len(out)} cards; incomplete: {missing}")


if __name__ == "__main__":
    main()
