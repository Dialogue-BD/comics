#!/usr/bin/env node
import fs from "node:fs";
import vm from "node:vm";
import { NURTURER_PART_1 } from "./nurturer-part1.mjs";
import { NURTURER_PART_2 } from "./nurturer-part2.mjs";
import { NURTURER_PART_3 } from "./nurturer-part3.mjs";

const root = new URL("../", import.meta.url);
const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(new URL("game-data.js", root), "utf8"), sandbox);

const gameData = sandbox.window.PICTURE_THIS_GAME_DATA;
const rawNurturer = {
  ...NURTURER_PART_1,
  ...NURTURER_PART_2,
  ...NURTURER_PART_3
};

const AFFIRM_OPENERS = [
  "Yes!",
  "Beautiful!",
  "That's right!",
  "You found it!",
  "Wonderful!",
  "Spot on!"
];

const output = {};
const errors = [];

for (const [cardIndex, cardId] of Object.keys(gameData).entries()) {
  const labels = gameData[cardId];
  const entries = rawNurturer[cardId];
  if (!Array.isArray(entries) || entries.length !== 6) {
    errors.push(`${cardId}: expected 6 nurturer entries, found ${entries ? entries.length : 0}`);
    continue;
  }

  output[cardId] = labels.map((label, itemIndex) => {
    const entry = entries[itemIndex];
    if (!Array.isArray(entry) || entry.length !== 3) {
      errors.push(`${cardId}[${itemIndex}] (${label}): invalid entry format`);
      return null;
    }
    const [ask, detail, collocations] = entry;
    if (!ask || typeof ask !== "string") errors.push(`${cardId}[${itemIndex}] (${label}): missing ask prompt`);
    if (!detail || typeof detail !== "string") errors.push(`${cardId}[${itemIndex}] (${label}): missing detail`);
    if (!Array.isArray(collocations) || collocations.length !== 3 || collocations.some(c => !c || typeof c !== "string")) {
      errors.push(`${cardId}[${itemIndex}] (${label}): expected 3 collocation strings`);
    }

    const opener = AFFIRM_OPENERS[(cardIndex + itemIndex) % AFFIRM_OPENERS.length];
    const cleanDetail = detail.trim().replace(/\.$/, "");
    const cleanCollocations = collocations.map(c => c.trim().replace(/^[a-z]/, ch => ch));

    return {
      label,
      ask: ask.trim(),
      yes: `${opener} That’s ${label} — ${cleanDetail}.`,
      recast: `That’s ${label} — ${cleanDetail}.`,
      collocations: cleanCollocations
    };
  });
}

if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

const fileContent = `// GPA (Growing Participator Approach) Nurturer prompts, affirmations, gentle recasts, and collocations.
// Generated by scripts/build-nurturer-data.mjs — covers all ${Object.keys(output).length} cards (${Object.keys(output).length * 6} items).
window.PICTURE_THIS_NURTURER_DATA = ${JSON.stringify(output, null, 2)};
`;

fs.writeFileSync(new URL("nurturer-data.js", root), fileContent, "utf8");
console.log(`PASS: Wrote nurturer-data.js for ${Object.keys(output).length} cards (${Object.keys(output).length * 6} items).`);
